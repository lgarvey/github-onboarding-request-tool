@dataclass
class Person:
    first_name: str
    last_name: str
    sso_id: str
    email: str
    github_login: str | None
    active: bool = True
    deactivated_at: date | None = None


@dataclass
class Demo:
    # file name → data for the world directory
    world: dict[str, dict] = field(default_factory=dict)
    # org → {"repositories": data, "teams": data}
    terraform: dict[str, dict[str, dict]] = field(default_factory=dict)


def _people(rng: random.Random) -> list[Person]:
    pairs = rng.sample([(f, last) for f in FIRST_NAMES for last in LAST_NAMES], 80)
    people, logins = [], set()
    for first, last in pairs:
        login = f"{first[0]}{last}".lower()
        suffix = 2
        while login in logins:
            login = f"{first[0]}{last}{suffix}".lower()
            suffix += 1
        logins.add(login)
        people.append(
            Person(
                first_name=first,
                last_name=last,
                sso_id=f"{first}.{last}-{rng.getrandbits(32):08x}@{SSO_DOMAIN}".lower(),
                email=f"{first}.{last}@{EMAIL_DOMAIN}".lower(),
                github_login=login,
            )
        )
    return people


class _Org:
    """Builds one organisation's teams and repositories config."""

    def __init__(self, name: str, display_name: str, admin_logins: list[str]):
        self.name = name
        self.display_name = display_name
        self.admin_logins = admin_logins
        self.teams: dict[str, dict] = {}
        self.repositories: dict[str, dict] = {}

    def team(self, slug, name, members, *, maintainers=1, parent=None, org_roles=(), about=None):
        """Add a team. `members` are people or bare logins; the first `maintainers` lead it."""
        roles = {}
        for index, member in enumerate(members):
            login = member if isinstance(member, str) else member.github_login
            if login and login not in roles:
                roles[login] = "maintainer" if index < maintainers else "member"
        entry = {
            "name": name,
            "slug": slug,
            "description": about,
            "privacy": "closed",
            "parent_team_id": stub_team_id(self.name, parent) if parent else None,
            "members": dict(sorted(roles.items())),
        }
        if org_roles:
            entry["organisation_role_names"] = list(org_roles)
        self.teams[slug] = entry

    def repos(self, names, about, *, main=None, admins=None, extra=None, users=None, rng):
        """Add repositories owned through `admins` (admin) and `main` (push, or maintain)."""
        for name in names:
            permissions = {"cyber": "pull"}
            if admins:
                permissions[admins] = "admin"
            if main:
                permissions[main] = "push" if admins else "maintain"
            permissions.update((extra or {}).get(name, {}))
            self.repositories[name] = {
                "name": name,
                "description": f"{about}: {name.split('-', 1)[-1].replace('-', ' ')}",
                "visibility": rng.choice(["internal", "private"]),
                "archived": False,
                "has_issues": True,
                "delete_branch_on_merge": True,
                "team_permissions": dict(sorted(permissions.items())),
                "user_permissions": dict(sorted((users or {}).get(name, {}).items())),
            }

    def config(self) -> dict[str, dict]:
        return {
            "repositories": {
                self.name: {"slug": self.name, "repositories": self.repositories},
            },
            "teams": {
                self.name: {
                    "slug": self.name,
                    "display_name": self.display_name,
                    "billing_email": f"github-billing@{EMAIL_DOMAIN}",
                    "description": f"{self.display_name} (synthetic demo organisation)",
                    "admin_logins": self.admin_logins,
                    "teams": self.teams,
                },
            },
        }


