class UnsafeTarget(Exception):
    pass


def _dump(data) -> str:
    return yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)


def _prepare(directory: Path) -> None:
    """Make sure `directory` is ours to overwrite: new, empty, or written by this module."""
    if (directory / ".git").exists():
        raise UnsafeTarget(f"{directory} is a git checkout. Refusing to overwrite it.")
    if directory.is_dir() and any(directory.iterdir()) and not (directory / MARKER).is_file():
        raise UnsafeTarget(
            f"{directory} already has files that generate_demo_world did not write "
            f"(there is no {MARKER}). Refusing to overwrite them."
        )
    directory.mkdir(parents=True, exist_ok=True)
    (directory / MARKER).write_text(
        "# Generated demo data\n\n"
        "Everything here is synthetic and written by `python manage.py generate_demo_world`.\n"
        "Re-run it rather than editing these files. The list of problems it plants is in\n"
        "`world/demo.py`.\n",
        encoding="utf-8",
    )


def write(world_dir: Path, terraform_dir: Path, schemas_dir: Path) -> list[Path]:
    """Write the demo world and its terraform tree. Returns the files written."""
    demo = build()
    for directory in (world_dir, terraform_dir):
        _prepare(directory)
    written = []
    for file, data in demo.world.items():
        path = world_dir / file
        path.write_text(HEADER + _dump(data), encoding="utf-8")
        written.append(path)

    for stale in ("terraform", "schemas"):
        shutil.rmtree(terraform_dir / stale, ignore_errors=True)
    if schemas_dir.is_dir():
        shutil.copytree(schemas_dir, terraform_dir / "schemas")
    for org, resources in demo.terraform.items():
        for resource, data in resources.items():
            path = terraform_dir / "terraform" / org / resource / "config.yaml"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("---\n" + _dump(data), encoding="utf-8")
            written.append(path)
    for directory in (world_dir, terraform_dir):
        _match_owner(directory)
    return written


def _match_owner(directory: Path) -> None:
    """Give everything under `directory` the owner of the directory it is in.

    The command often runs as root in a container, and the checkout belongs to someone else.
    """
    owner = directory.resolve().parent.stat()
    for root, directories, files in os.walk(directory):
        for name in [".", *directories, *files]:
            try:
                os.chown(Path(root) / name, owner.st_uid, owner.st_gid)
            except PermissionError:
                return
